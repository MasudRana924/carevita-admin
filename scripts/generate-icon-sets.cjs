// Bundles every `solar:*` icon referenced in src/ into src/components/iconify/icon-sets.ts
// so icons render offline without hitting the Iconify API. Run: npm run icons:build

const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const SRC = path.join(ROOT, 'src');
const OUT = path.join(SRC, 'components', 'iconify', 'icon-sets.ts');
const solar = require('@iconify-json/solar/icons.json');

const used = new Set();
(function walk(dir) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) walk(full);
    else if (/\.(tsx?|jsx?)$/.test(entry.name) && full !== OUT) {
      for (const m of fs.readFileSync(full, 'utf8').matchAll(/['"`]solar:([a-z0-9-]+)['"`]/g)) used.add(m[1]);
    }
  }
})(SRC);

const icons = {};
const aliases = {};
const missing = [];
for (const name of [...used].sort()) {
  if (solar.icons[name]) {
    icons[name] = solar.icons[name];
  } else if (solar.aliases?.[name]) {
    aliases[name] = solar.aliases[name];
    const parent = solar.aliases[name].parent;
    if (solar.icons[parent]) icons[parent] = solar.icons[parent];
  } else {
    missing.push(name);
  }
}

const collection = {
  prefix: 'solar',
  width: solar.width,
  height: solar.height,
  icons,
  ...(Object.keys(aliases).length ? { aliases } : {}),
};

fs.writeFileSync(
  OUT,
  `// Generated by scripts/generate-icon-sets.cjs — do not edit by hand.\n\nimport type { IconifyJSON } from '@iconify/react';\n\nconst solarIcons: IconifyJSON = ${JSON.stringify(collection, null, 2)};\n\nexport default solarIcons;\n`
);

console.log(`Bundled ${Object.keys(icons).length} solar icons.`);
if (missing.length) {
  console.error(`Unknown solar icons: ${missing.join(', ')}`);
  process.exitCode = 1;
}
